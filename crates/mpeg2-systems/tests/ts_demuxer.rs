    /// Transport Streams FFmpeg wrote, generated by `cargo xtask fixtures`
    /// (188) and carried over from the previous implementation (192, 204):
    /// the same packets in each framing
    ///
    /// Packet 1 carries the PAT, packet 2 the PMT on PID 0x1000, and packet
    /// 3 the first PCR, on the video PID 0x100.
    const STANDARD_188: &[u8] = include_bytes!("fixtures/188.ts");
    const TIMESTAMPED_192: &[u8] = include_bytes!("fixtures/192.ts");
    const REED_SOLOMON_204: &[u8] = include_bytes!("fixtures/204.ts");

    /// An [`Event`] with what it lends copied out of the demuxer
    #[derive(Debug, Clone, PartialEq, Eq)]
    enum Seen {
        SyncAcquired(PacketSize),
        Unsynchronized(Vec<u8>),
        ProgramClockReference {
            pid: u16,
            program_clock_reference: ClockReference,
        },
        Section {
            pid: u16,
            table_id: u8,
            private_indicator: bool,
            reserved_before_section_length: u8,
            syntax: Option<SectionSyntax>,
            body: Vec<u8>,
        },
        ProgramAssociationSection {
            transport_stream_id: u16,
            version_number: VersionNumber,
            current_next_indicator: bool,
            section_number: u8,
            last_section_number: u8,
            programs: Vec<Program>,
        },
        TsProgramMapSection {
            pid: u16,
            program_number: u16,
            version_number: VersionNumber,
            current_next_indicator: bool,
            section_number: u8,
            last_section_number: u8,
            pcr_pid: Option<u16>,
            program_info: Vec<u8>,
            /// `stream_type`, `elementary_PID` and `ES_info` of each stream
            elementary_streams: Vec<(u8, u16, Vec<u8>)>,
        },
        CaSection {
            version_number: VersionNumber,
            current_next_indicator: bool,
            section_number: u8,
            last_section_number: u8,
            descriptors: Vec<u8>,
        },
        /// A PES packet, its payload by length
        PesPacket {
            pid: u16,
            stream_id: u8,
            pts: Option<u64>,
            dts: Option<u64>,
            payload_length: usize,
            start_offset: u64,
        },
        UnreadablePesPacket {
            pid: u16,
            bytes: Vec<u8>,
            error: pes::Error,
            start_offset: u64,
        },
        TruncatedPesPacket {
            pid: u16,
            bytes: Vec<u8>,
            start_offset: u64,
        },
        Error(Error),
        /// An event this test does not expect, so the comparison fails on it
        Unexpected(String),
    }

    fn drain(demuxer: &mut Demuxer, seen: &mut Vec<Seen>) {
        while let Some(event) = demuxer.poll_event() {
            seen.push(seen_event(event));
        }
    }

    fn seen_event(event: Event<'_>) -> Seen {
        match event {
            Event::SyncAcquired { packet_size } => Seen::SyncAcquired(packet_size),
            Event::Unsynchronized { bytes } => Seen::Unsynchronized(bytes.to_vec()),
            Event::ProgramClockReference {
                pid,
                program_clock_reference,
            } => Seen::ProgramClockReference {
                pid: pid.get(),
                program_clock_reference,
            },
            Event::Section { pid, section } => seen_section(pid.get(), &section),
            Event::ProgramAssociationSection(section) => Seen::ProgramAssociationSection {
                transport_stream_id: section.transport_stream_id,
                version_number: section.version_number,
                current_next_indicator: section.current_next_indicator,
                section_number: section.section_number,
                last_section_number: section.last_section_number,
                programs: section.programs.iter().map(Result::unwrap).collect(),
            },
            Event::TsProgramMapSection { pid, section } => Seen::TsProgramMapSection {
                pid: pid.get(),
                program_number: section.program_number,
                version_number: section.version_number,
                current_next_indicator: section.current_next_indicator,
                section_number: section.section_number,
                last_section_number: section.last_section_number,
                pcr_pid: section.pcr_pid.map(Pid::get),
                program_info: section.program_info.as_bytes().to_vec(),
                elementary_streams: section
                    .elementary_streams
                    .iter()
                    .map(Result::unwrap)
                    .map(|stream| {
                        (
                            stream.stream_type.get(),
                            stream.elementary_pid.get(),
                            stream.es_info.as_bytes().to_vec(),
                        )
                    })
                    .collect(),
            },
            Event::CaSection(section) => Seen::CaSection {
                version_number: section.version_number,
                current_next_indicator: section.current_next_indicator,
                section_number: section.section_number,
                last_section_number: section.last_section_number,
                descriptors: section.descriptors.as_bytes().to_vec(),
            },
            Event::PesPacket {
                pid,
                packet,
                start_offset,
            } => Seen::PesPacket {
                pid: pid.get(),
                stream_id: packet.stream_id.get(),
                pts: packet
                    .optional_header
                    .as_ref()
                    .and_then(|header| header.pts)
                    .map(|pts| pts.get()),
                dts: packet
                    .optional_header
                    .as_ref()
                    .and_then(|header| header.dts)
                    .map(|dts| dts.get()),
                payload_length: packet.payload.len(),
                start_offset,
            },
            Event::UnreadablePesPacket {
                pid,
                bytes,
                error,
                start_offset,
            } => Seen::UnreadablePesPacket {
                pid: pid.get(),
                bytes: bytes.to_vec(),
                error,
                start_offset,
            },
            Event::TruncatedPesPacket {
                pid,
                bytes,
                start_offset,
            } => Seen::TruncatedPesPacket {
                pid: pid.get(),
                bytes: bytes.to_vec(),
                start_offset,
            },
            Event::Error(error) => Seen::Error(error),
            other => Seen::Unexpected(format!("{other:?}")),
        }
    }

    fn demux(stream: &[u8], chunk_length: usize) -> Vec<Seen> {
        let mut demuxer = Demuxer::new(DemuxerConfig::default());
        let mut seen = Vec::new();
        for chunk in stream.chunks(chunk_length) {
            demuxer.handle_input(chunk);
            drain(&mut demuxer, &mut seen);
        }
        demuxer.finish();
        drain(&mut demuxer, &mut seen);
        seen
    }

    fn seen_section(pid: u16, section: &Section<'_>) -> Seen {
        Seen::Section {
            pid,
            table_id: section.table_id.get(),
            private_indicator: section.private_indicator,
            reserved_before_section_length: section.reserved_before_section_length,
            syntax: section.syntax,
            body: section.body.to_vec(),
        }
    }

    fn version(value: u8) -> VersionNumber {
        VersionNumber::try_from(value).unwrap()
    }

    /// The PAT of the fixture, `transport_stream_id` 1 naming program 1 on
    /// PID 0x1000, as the previous implementation reported it
    fn pat() -> Seen {
        pat_of(0, vec![program(1, 0x1000)])
    }

    fn pat_of(version_number: u8, programs: Vec<Program>) -> Seen {
        Seen::ProgramAssociationSection {
            transport_stream_id: 1,
            version_number: version(version_number),
            current_next_indicator: true,
            section_number: 0,
            last_section_number: 0,
            programs,
        }
    }

    fn program(program_number: u16, program_map_pid: u16) -> Program {
        Program::ProgramMap {
            program_number: NonZeroU16::new(program_number).unwrap(),
            program_map_pid: Pid::try_from(program_map_pid).unwrap(),
        }
    }

    /// The PMT of the fixture, its PCR on the video PID 0x100 and its audio
    /// on 0x101, as the previous implementation reported it
    fn pmt() -> Seen {
        Seen::TsProgramMapSection {
            pid: 0x1000,
            program_number: 1,
            version_number: version(0),
            current_next_indicator: true,
            section_number: 0,
            last_section_number: 0,
            pcr_pid: Some(0x0100),
            program_info: Vec::new(),
            elementary_streams: vec![(0x02, 0x0100, Vec::new()), (0x03, 0x0101, Vec::new())],
        }
    }

    fn pcr(base: u64) -> Seen {
        Seen::ProgramClockReference {
            pid: 0x0100,
            program_clock_reference: ClockReference::new(base, 0).unwrap(),
        }
    }

    /// The events of the fixture after `SyncAcquired`, in packet order, as
    /// read from it with a script independent of this crate: the PAT and PMT
    /// the fixture resends at the same version come once
    fn fixture_events() -> Vec<Seen> {
        vec![pat(), pmt(), pcr(63_000), pcr(81_000), pcr(99_000)]
    }

    fn acquired_then(packet_size: PacketSize, rest: Vec<Seen>) -> Vec<Seen> {
        let mut seen = vec![Seen::SyncAcquired(packet_size)];
        seen.extend(rest);
        seen
    }

    /// The fixture with packet `index` removed
    fn without_packet(index: usize) -> Vec<u8> {
        let mut stream = STANDARD_188.to_vec();
        stream.drain(188 * index..188 * (index + 1));
        stream
    }

    #[test]
    fn the_pat_pmt_and_pcrs_of_every_framing_are_reported_whatever_the_chunk_length() {
        for (stream, packet_size) in [
            (STANDARD_188, PacketSize::Standard188),
            (TIMESTAMPED_192, PacketSize::Timestamped192),
            (REED_SOLOMON_204, PacketSize::ReedSolomon204),
        ] {
            for chunk_length in [1, 7, 188, 1000, stream.len()] {
                assert_eq!(
                    demux(stream, chunk_length),
                    acquired_then(packet_size, fixture_events()),
                    "{packet_size:?} in chunks of {chunk_length}"
                );
            }
        }
    }

    #[test]
    fn garbage_before_the_stream_is_reported_with_its_bytes_before_sync() {
        let mut stream = vec![0xFF; 500];
        stream.extend_from_slice(STANDARD_188);
        let mut expected = vec![Seen::Unsynchronized(vec![0xFF; 500])];
        expected.extend(acquired_then(PacketSize::Standard188, fixture_events()));
        assert_eq!(demux(&stream, 1000), expected);
    }

