//! The Transport Stream demuxer over streams FFmpeg wrote, whole, behind
//! garbage, cut short, and with packets altered

#[cfg(test)]
#[cfg(feature = "alloc")]
#[expect(
    clippy::indexing_slicing,
    clippy::arithmetic_side_effects,
    reason = "streams are cut at constant offsets well inside their length"
)]
mod tests {
    use mpeg2_systems::psi::TableId;
    use mpeg2_systems::psi::section::{self, Section, SectionSyntax};
    use mpeg2_systems::time::ClockReference;
    use mpeg2_systems::ts::demux::{Demuxer, DemuxerConfig, Error, Event, PacketSize};
    use mpeg2_systems::ts::{ContinuityCounter, Pid};

    /// Transport Streams FFmpeg wrote, generated by `cargo xtask fixtures`
    /// (188) and carried over from the previous implementation (192, 204):
    /// the same packets in each framing
    ///
    /// Packet 1 carries the PAT, packet 2 the PMT on PID 0x1000, and packet
    /// 3 the first PCR, on the video PID 0x100.
    const STANDARD_188: &[u8] = include_bytes!("fixtures/188.ts");
    const TIMESTAMPED_192: &[u8] = include_bytes!("fixtures/192.ts");
    const REED_SOLOMON_204: &[u8] = include_bytes!("fixtures/204.ts");

    /// An [`Event`] with what it lends copied out of the demuxer
    #[derive(Debug, PartialEq, Eq)]
    enum Seen {
        SyncAcquired(PacketSize),
        Unsynchronized(Vec<u8>),
        ProgramClockReference {
            pid: u16,
            program_clock_reference: ClockReference,
        },
        Section {
            pid: u16,
            table_id: u8,
            private_indicator: bool,
            reserved_before_section_length: u8,
            syntax: Option<SectionSyntax>,
            body: Vec<u8>,
        },
        Error(Error),
        /// An event this test does not expect, so the comparison fails on it
        Unexpected(String),
    }

    fn drain(demuxer: &mut Demuxer, seen: &mut Vec<Seen>) {
        while let Some(event) = demuxer.poll_event() {
            seen.push(seen_event(event));
        }
    }

    fn seen_event(event: Event<'_>) -> Seen {
        match event {
            Event::SyncAcquired { packet_size } => Seen::SyncAcquired(packet_size),
            Event::Unsynchronized { bytes } => Seen::Unsynchronized(bytes.to_vec()),
            Event::ProgramClockReference {
                pid,
                program_clock_reference,
            } => Seen::ProgramClockReference {
                pid: pid.get(),
                program_clock_reference,
            },
            Event::Section { pid, section } => seen_section(pid.get(), &section),
            Event::Error(error) => Seen::Error(error),
            other => Seen::Unexpected(format!("{other:?}")),
        }
    }

    fn demux(stream: &[u8], chunk_length: usize) -> Vec<Seen> {
        let mut demuxer = Demuxer::new(DemuxerConfig::default());
        let mut seen = Vec::new();
        for chunk in stream.chunks(chunk_length) {
            demuxer.handle_input(chunk);
            drain(&mut demuxer, &mut seen);
        }
        demuxer.finish();
        drain(&mut demuxer, &mut seen);
        seen
    }

    fn seen_section(pid: u16, section: &Section<'_>) -> Seen {
        Seen::Section {
            pid,
            table_id: section.table_id.get(),
            private_indicator: section.private_indicator,
            reserved_before_section_length: section.reserved_before_section_length,
            syntax: section.syntax,
            body: section.body.to_vec(),
        }
    }

    /// The section that starts packet `index` of the fixture, read directly
    /// from its bytes
    fn fixture_section(pid: u16, index: usize) -> Seen {
        let packet = &STANDARD_188[188 * index..188 * (index + 1)];
        let start = 5 + usize::from(packet[4]);
        let length = 3 + usize::from(u16::from_be_bytes([
            packet[start + 1] & 0x0F,
            packet[start + 2],
        ]));
        seen_section(pid, &Section::read(&packet[start..start + length]).unwrap())
    }

    fn pat() -> Seen {
        fixture_section(0x0000, 1)
    }

    fn pmt() -> Seen {
        fixture_section(0x1000, 2)
    }

    fn pcr(base: u64) -> Seen {
        Seen::ProgramClockReference {
            pid: 0x0100,
            program_clock_reference: ClockReference::new(base, 0).unwrap(),
        }
    }

    /// The events of the fixture after `SyncAcquired`, in packet order, as
    /// read from it with a script independent of this crate
    fn fixture_events() -> Vec<Seen> {
        vec![
            pat(),
            pmt(),
            pcr(63_000),
            pat(),
            pmt(),
            pcr(81_000),
            pat(),
            pmt(),
            pcr(99_000),
            pat(),
            pmt(),
        ]
    }

    fn acquired_then(packet_size: PacketSize, rest: Vec<Seen>) -> Vec<Seen> {
        let mut seen = vec![Seen::SyncAcquired(packet_size)];
        seen.extend(rest);
        seen
    }

    /// The fixture with packet `index` removed
    fn without_packet(index: usize) -> Vec<u8> {
        let mut stream = STANDARD_188.to_vec();
        stream.drain(188 * index..188 * (index + 1));
        stream
    }

    #[test]
    fn the_pat_pmt_and_pcrs_of_every_framing_are_reported_whatever_the_chunk_length() {
        for (stream, packet_size) in [
            (STANDARD_188, PacketSize::Standard188),
            (TIMESTAMPED_192, PacketSize::Timestamped192),
            (REED_SOLOMON_204, PacketSize::ReedSolomon204),
        ] {
            for chunk_length in [1, 7, 188, 1000, stream.len()] {
                assert_eq!(
                    demux(stream, chunk_length),
                    acquired_then(packet_size, fixture_events()),
                    "{packet_size:?} in chunks of {chunk_length}"
                );
            }
        }
    }

    #[test]
    fn garbage_before_the_stream_is_reported_with_its_bytes_before_sync() {
        let mut stream = vec![0xFF; 500];
        stream.extend_from_slice(STANDARD_188);
        let mut expected = vec![Seen::Unsynchronized(vec![0xFF; 500])];
        expected.extend(acquired_then(PacketSize::Standard188, fixture_events()));
        assert_eq!(demux(&stream, 1000), expected);
    }

    #[test]
    fn a_stream_cut_inside_its_last_packet_reports_the_partial_packet_at_the_end() {
        let stream = &STANDARD_188[..STANDARD_188.len() - 100];
        let mut expected = acquired_then(PacketSize::Standard188, fixture_events());
        expected.push(Seen::Unsynchronized(stream[stream.len() - 88..].to_vec()));
        assert_eq!(demux(stream, 1000), expected);
    }

    #[test]
    fn a_192_byte_stream_cut_inside_a_timestamp_is_unsynchronized_up_to_its_next_unit() {
        let stream = &TIMESTAMPED_192[2..];
        let mut expected = vec![Seen::Unsynchronized(stream[..190].to_vec())];
        expected.extend(acquired_then(PacketSize::Timestamped192, fixture_events()));
        for chunk_length in [1, 7, 188, 1000, stream.len()] {
            assert_eq!(
                demux(stream, chunk_length),
                expected,
                "in chunks of {chunk_length}"
            );
        }
    }

    #[test]
    fn a_192_byte_stream_cut_between_units_leaves_nothing_at_the_end() {
        let stream = &TIMESTAMPED_192[..TIMESTAMPED_192.len() - 192];
        assert_eq!(
            demux(stream, 1000),
            acquired_then(PacketSize::Timestamped192, fixture_events())
        );
    }

    #[test]
    fn a_stream_resynchronizes_after_two_missing_sync_bytes_without_a_false_discontinuity() {
        let mut stream = STANDARD_188.to_vec();
        stream[188 * 10] = 0x00;
        stream[188 * 11] = 0x00;
        let mut expected = acquired_then(PacketSize::Standard188, vec![pat(), pmt(), pcr(63_000)]);
        expected.extend([
            Seen::Error(Error::SyncByteMissing { found: 0x00 }),
            Seen::Error(Error::SyncLost),
            Seen::Unsynchronized(stream[188 * 11..188 * 12].to_vec()),
            Seen::SyncAcquired(PacketSize::Standard188),
        ]);
        expected.extend(fixture_events().into_iter().skip(3));
        assert_eq!(demux(&stream, 1000), expected);
    }

    #[test]
    fn a_skipped_continuity_counter_is_reported_once() {
        let mut expected = acquired_then(PacketSize::Standard188, vec![pat(), pmt(), pcr(63_000)]);
        expected.push(Seen::Error(Error::Discontinuity {
            pid: Pid::try_from(0x0100).unwrap(),
            expected: ContinuityCounter::try_from(2).unwrap(),
            found: ContinuityCounter::try_from(3).unwrap(),
        }));
        expected.extend(fixture_events().into_iter().skip(3));
        assert_eq!(demux(&without_packet(5), 1000), expected);
    }

    #[test]
    fn a_section_whose_crc_32_fails_is_reported_and_the_next_one_is_reassembled() {
        let mut stream = STANDARD_188.to_vec();
        stream[188 + 20] ^= 0x01;
        let seen = demux(&stream, 1000);
        let crc_error = Error::Section {
            pid: Pid::PAT,
            error: section::Error::Crc32 {
                crc_32: 0x2AB1_04B3,
                computed: 0x2AB1_04B2,
            },
        };
        // Why no PMT from packet 2: the PAT that names its PID is the one that failed
        let mut expected = acquired_then(
            PacketSize::Standard188,
            vec![Seen::Error(crc_error), pcr(63_000)],
        );
        expected.extend(fixture_events().into_iter().skip(3));
        assert_eq!(seen, expected);
    }

    #[test]
    fn a_packet_with_transport_error_indicator_set_reports_nothing_else() {
        let mut stream = STANDARD_188.to_vec();
        stream[188 * 3 + 1] |= 0x80;
        let mut expected = acquired_then(PacketSize::Standard188, vec![pat(), pmt()]);
        expected.push(Seen::Error(Error::TransportErrorIndicator {
            pid: Pid::try_from(0x0100).unwrap(),
        }));
        expected.extend(fixture_events().into_iter().skip(3));
        assert_eq!(demux(&stream, 1000), expected);
    }

    #[test]
    fn one_duplicate_packet_is_passed_over_and_a_second_is_a_discontinuity() {
        let packet = &STANDARD_188[188..188 * 2];
        let with_copies = |copies: usize| {
            let mut stream = STANDARD_188[..188 * 2].to_vec();
            for _ in 0..copies {
                stream.extend_from_slice(packet);
            }
            stream.extend_from_slice(&STANDARD_188[188 * 2..]);
            stream
        };
        assert_eq!(
            demux(&with_copies(1), 1000),
            acquired_then(PacketSize::Standard188, fixture_events())
        );
        let mut expected = acquired_then(PacketSize::Standard188, vec![pat()]);
        expected.extend([
            Seen::Error(Error::Discontinuity {
                pid: Pid::PAT,
                expected: ContinuityCounter::try_from(1).unwrap(),
                found: ContinuityCounter::try_from(0).unwrap(),
            }),
            pat(),
        ]);
        expected.extend(fixture_events().into_iter().skip(1));
        assert_eq!(demux(&with_copies(2), 1000), expected);
    }

    /// A Transport Packet laid out by hand: the header, an adaptation field
    /// of `adaptation_field` bytes (its length byte not included) if any, then
    /// `payload` if any, padded with 0xFF
    fn packet(
        pid: u16,
        payload_unit_start_indicator: bool,
        continuity_counter: u8,
        adaptation_field: Option<&[u8]>,
        payload: Option<&[u8]>,
    ) -> Vec<u8> {
        let [high, low] = pid.to_be_bytes();
        let adaptation_field_control = match (adaptation_field, payload) {
            (None, _) => 0x10,
            (Some(_), None) => 0x20,
            (Some(_), Some(_)) => 0x30,
        };
        let mut bytes = vec![
            0x47,
            high | if payload_unit_start_indicator {
                0x40
            } else {
                0
            },
            low,
            adaptation_field_control | continuity_counter,
        ];
        if let Some(field) = adaptation_field {
            let length = if payload.is_some() { field.len() } else { 183 };
            bytes.push(u8::try_from(length).unwrap());
            bytes.extend_from_slice(field);
            bytes.resize(5 + length, 0xFF);
        }
        bytes.extend_from_slice(payload.unwrap_or_default());
        bytes.resize(188, 0xFF);
        bytes
    }

    /// A short-form section of `table_id` with `body`, which carries no
    /// `CRC_32`
    fn short_section(table_id: u8, body: &[u8]) -> Vec<u8> {
        let [high, low] = u16::try_from(body.len()).unwrap().to_be_bytes();
        let mut bytes = vec![table_id, 0x30 | high, low];
        bytes.extend_from_slice(body);
        bytes
    }

    /// Null packets enough to acquire the grid, then `packets`
    fn behind_null_packets(packets: &[Vec<u8>]) -> Vec<u8> {
        let mut stream = Vec::new();
        for _ in 0..5 {
            stream.extend(packet(0x1FFF, false, 0, None, Some(&[])));
        }
        for bytes in packets {
            stream.extend_from_slice(bytes);
        }
        stream
    }

    #[test]
    fn sections_inside_one_packet_and_across_packets_are_reported_in_order() {
        let whole = short_section(0x80, &[0xAA; 20]);
        let across = short_section(0x81, &[0xBB; 300]);
        let after = short_section(0x82, &[0xCC; 10]);
        // Why split there: the head must run to the end of the packet, or
        // the padding after it would be read as more of the section
        let (head, tail) = across.split_at(184 - 1 - whole.len());
        let first = [&[0x00][..], &whole, head].concat();
        let second = [&[u8::try_from(tail.len()).unwrap()][..], tail, &after].concat();
        let stream = behind_null_packets(&[
            packet(0x0000, true, 0, None, Some(&first)),
            packet(0x0000, true, 1, None, Some(&second)),
        ]);
        let expected = acquired_then(
            PacketSize::Standard188,
            vec![
                seen_section(0x0000, &Section::new(TableId::from(0x80), &[0xAA; 20])),
                seen_section(0x0000, &Section::new(TableId::from(0x81), &[0xBB; 300])),
                seen_section(0x0000, &Section::new(TableId::from(0x82), &[0xCC; 10])),
            ],
        );
        for chunk_length in [1, 7, 188, 1000, stream.len()] {
            assert_eq!(
                demux(&stream, chunk_length),
                expected,
                "in chunks of {chunk_length}"
            );
        }
    }

    #[test]
    fn a_discontinuity_indicator_without_payload_drops_the_section_in_flight_and_sets_the_counter()
    {
        let across = short_section(0x80, &[0xBB; 300]);
        let (head, tail) = across.split_at(184 - 1);
        let stream = behind_null_packets(&[
            packet(0x0000, true, 0, None, Some(&[&[0x00][..], head].concat())),
            packet(0x0000, false, 5, Some(&[0x80]), None),
            packet(0x0000, false, 6, None, Some(tail)),
        ]);
        assert_eq!(
            demux(&stream, 1000),
            acquired_then(PacketSize::Standard188, Vec::new())
        );
    }

    #[test]
    fn a_section_lent_from_a_packet_keeps_its_bytes_across_more_input() {
        let first = short_section(0x80, &[0xAA; 7]);
        let second = short_section(0x80, &[0xBB; 5]);
        let stream = behind_null_packets(&[packet(
            0x0001,
            true,
            0,
            None,
            Some(&[&[0x00][..], &first, &second].concat()),
        )]);
        let more = packet(0x1FFF, false, 0, None, Some(&[]));
        for next_input in [&[][..], &more[..]] {
            let mut demuxer = Demuxer::new(DemuxerConfig::default());
            demuxer.handle_input(&stream);
            let mut seen = vec![
                seen_event(demuxer.poll_event().unwrap()),
                seen_event(demuxer.poll_event().unwrap()),
            ];
            demuxer.handle_input(next_input);
            seen.push(seen_event(demuxer.poll_event().unwrap()));
            assert_eq!(
                seen,
                [
                    Seen::SyncAcquired(PacketSize::Standard188),
                    seen_section(0x0001, &Section::new(TableId::from(0x80), &[0xAA; 7])),
                    seen_section(0x0001, &Section::new(TableId::from(0x80), &[0xBB; 5])),
                ],
                "after {} more bytes",
                next_input.len()
            );
        }
    }

    #[test]
    fn a_clone_equals_the_demuxer_it_was_cloned_from() {
        let mut demuxer = Demuxer::new(DemuxerConfig::default());
        demuxer.handle_input(&STANDARD_188[..1000]);
        let _ = demuxer.poll_event();
        assert_eq!(demuxer.clone(), demuxer);
    }

    #[test]
    fn demuxers_fed_the_same_input_in_different_chunks_are_equal_once_drained() {
        let drained = |chunk_length: usize| {
            let mut demuxer = Demuxer::new(DemuxerConfig::default());
            for chunk in STANDARD_188[..5000].chunks(chunk_length) {
                demuxer.handle_input(chunk);
                while demuxer.poll_event().is_some() {}
            }
            demuxer
        };
        assert_eq!(drained(7), drained(1000));
    }

    #[test]
    #[should_panic(expected = "after finish")]
    fn input_handed_over_before_the_end_is_drained_is_refused() {
        let mut demuxer = Demuxer::new(DemuxerConfig::default());
        demuxer.handle_input(STANDARD_188);
        demuxer.finish();
        demuxer.handle_input(STANDARD_188);
    }
}
